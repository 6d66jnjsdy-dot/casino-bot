def format_hand_horizontal(hand):
    """
    מקבל רשימה של קלפים (לדוגמה: [('A', 'Spades'), ('10', 'Hearts')]) 
    ומחזיר מחרוזת שבה הקלפים מוצגים אחד ליד השני בצורה אופקית נקייה
    """
    lines = ["", "", ""]
    for rank, suit in hand:
        art = CARDS_EMBED_ART.get(suit, {}).get(rank, "╭───╮\n│?  │\n╰───╯")
        split_art = art.split('\n')
        for i in range(3):
            lines[i] += split_art[i] + " "
    return "\n".join(lines)
